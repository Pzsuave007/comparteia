export function useT(lang) {
  const l = T[lang] ? lang : "es";
  return (key) => T[l][key] ?? T.es[key] ?? key;
}

export function tt(lang, key) {
  const l = T[lang] ? lang : "es";
  return T[l][key] ?? T.es[key] ?? key;
}

// pick localized field from an entity/question translations object
export function loc(obj, lang, field = "name") {
  if (!obj || !obj.translations) return "";
  const tr = obj.translations[lang] || obj.translations.es || Object.values(obj.translations)[0];
  return tr ? tr[field] : "";
}
